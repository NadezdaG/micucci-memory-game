<script>
import spinner from "./components/spinner.vue";
import popup from "./components/popup.vue";
import card from "./components/card.vue";

import WooCommerceRestApi from "@woocommerce/woocommerce-rest-api";
const _ = require("lodash");

export default {
  name: "App",
  components: { spinner, popup, card },
  data() {
    return {
      mobileNav: false,
      loading: true,
      categories: {
        pendants: 21,
      },
      memoryCards: [],
      flippedCards: [],
      matchCard: {},
      category: 21,
      count: {
        simple: 4,
        medium: 8,
        hard: 12,
      },
      dificulty: "hard",
    };
  },
  watch: {
    dificulty() {
      this.reloadCards();
    },
    category() {
      this.reloadCards();
    },
  },
  methods: {
    loadData(category) {
        console.log('loaded');
      const api = new WooCommerceRestApi({
        url: "https://www.bijoure.com",
        consumerKey: "ck_6455f743ae39dcc151f659bf21b90856ebea7c4a",
        consumerSecret: "cs_baf9feee3c62284a9054d08f17a95d46562df7c7",
        version: "wc/v3",
      });
      api
        .get("products", {
          per_page: 100,
          category: category,
        })
        .then((response) => {
            console.log('downloacded');
          const arr = [];
          response.data.forEach((item) => {
            arr.push({
              id: item.id,
              name: item.name,
              permalink: item.permalink,
              image: item.images[0]["src"],
              isFlipped: false,
              isMatched: false,
            });
          });
          localStorage.setItem("memoryCards-" + category, JSON.stringify(arr));
          this.shuffleMemoryCards(arr);
        })
        .catch((error) => {
          console.log(error.response.data);
        });
    },

    reloadCards() {
      this.mobileNav = false;
      this.loading = true;
      this.memoryCards = [];
      this.flippedCards = [];
      this.matchCard = {};
      this.loadCards();
    },

    shuffleMemoryCards(array) {
      array = array.slice(0, this.count[this.dificulty]);
      this.memoryCards = _.shuffle(array.concat(_.cloneDeep(array)));
      this.loading = false;
    },

    loadCards() {
      if (localStorage.getItem("memoryCards-" + this.category)) {
        let tempArray = JSON.parse(
          localStorage.getItem("memoryCards-" + this.category) || "[]"
        );
        this.shuffleMemoryCards(tempArray);
      } else {
        this.loadData(this.category);
      }
    },

    flipCard(card) {
      if (card.isMatched === true) {
        this.matchCard = card;
        this.$refs.popup.openPopup();
        return;
      }
      if (this.flippedCards.length < 2) {
        card.isFlipped = !card.isFlipped;
        this.flippedCards.push(card);
        if (this.flippedCards.length === 2) {
          this.match();
        }
      } else {
        this.memoryCards.forEach((card) => (card.isFlipped = false));
        this.flippedCards = [];
      }
    },

    match() {
      if (this.flippedCards[0].name === this.flippedCards[1].name) {
        this.matchCard = this.flippedCards[0];
        this.flippedCards.forEach((card) => (card.isMatched = true));
        this.flippedCards = [];
        this.$refs.popup.openPopup();
      }
    },
  },
  mounted: function () {
    this.loadCards();
  },
};
</script>

